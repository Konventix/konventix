<?php

declare(strict_types=1);

namespace Konventix\Support\Links;

use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\URL;
use Konventix\Platform\Brands\BrandUrl;
use Konventix\Platform\Models\Brand;
use Konventix\Platform\Operators\OperatorSettings;
use Konventix\Support\Models\SupportRequest;

/**
 * Every link a Support mail carries, in one place, and every one of them
 * absolute.
 *
 * Absolute is not a nicety here. A report can be filed on any of an
 * operator's brand hosts or on the console, and the mail that answers it is
 * rendered wherever the listener happens to run — during the request today,
 * in a queue worker the moment sends are deferred. A relative path in a
 * mail opens on whichever host the reader's client guesses, which for the
 * console path is a brand host that rejects it. This is the same rule, and
 * the same `OperatorSettings::adminBaseUrlForBrand()` doorway, that
 * `Commerce\Operations\AdminUrl` states for shop-operator notices — copied
 * rather than imported, because a module may not reach into another
 * module's internals (ADR-0004, `ArchitectureTest`), and extended for the
 * case Commerce never has: a report with **no brand at all**.
 *
 * **The reporter routes do not exist yet.** They are S3 (#307), and this
 * slice ships the mail that links to them. So every link is generated by
 * route name *if the route is registered* and falls back to the path S3
 * will register otherwise — which keeps this slice's mails correct and
 * makes S3's job "register the route", not "find the four places that
 * hard-coded its path". The `Route::has()` checks and the literal paths
 * below are the TODOs; delete them in S3 and S2 respectively.
 */
final class SupportLinks
{
    /** How long a guest's access link lives (design §8.2, D-SUP-07). */
    public const int GUEST_LINK_DAYS = 30;

    /** TODO(S3, #307): register `support.requests.show` and drop the literal. */
    private const string GUEST_ROUTE = 'support.requests.show';

    /** TODO(S3, #307): register `support.requests.mine.show` and drop the literal. */
    private const string ACCOUNT_ROUTE = 'support.requests.mine.show';

    /** TODO(S2, #306): register `admin.support.requests.show` and drop the literal. */
    private const string CONSOLE_ROUTE = 'admin.support.requests.show';

    public function __construct(
        private readonly BrandUrl $brandUrl,
        private readonly OperatorSettings $operatorSettings,
    ) {}

    /**
     * Where the reporter follows their own report.
     *
     * An account gets a plain link to "My support requests" — the session
     * is the authorization. A guest gets a signed link valid for 30 days,
     * because the mail *is* their only key to the request (§8.2), which is
     * also why the receipt is sent whether or not they consented to being
     * contacted.
     */
    public function reporterUrl(SupportRequest $request): string
    {
        $id = (string) $request->getKey();

        if ($request->user_id !== null) {
            return $this->onBrand(
                $request->filed_on_brand_id,
                Route::has(self::ACCOUNT_ROUTE)
                    ? route(self::ACCOUNT_ROUTE, ['request' => $id], absolute: false)
                    : '/my/support-requests/'.$id,
            );
        }

        if (Route::has(self::GUEST_ROUTE)) {
            return URL::temporarySignedRoute(
                self::GUEST_ROUTE,
                now()->addDays(self::GUEST_LINK_DAYS),
                ['request' => $id],
            );
        }

        return $this->onBrand($request->filed_on_brand_id, '/support/requests/'.$id);
    }

    /**
     * Where an operator opens the report in the console.
     */
    public function consoleUrl(SupportRequest $request): string
    {
        $id = (string) $request->getKey();

        $path = Route::has(self::CONSOLE_ROUTE)
            ? route(self::CONSOLE_ROUTE, ['request' => $id], absolute: false)
            : '/admin/support-requests/'.$id;

        return $this->onConsole($request->filed_on_brand_id, $path);
    }

    /**
     * The brand's own origin, or the deployment's when the report was filed
     * on the console or the brand answers on no host yet.
     */
    private function onBrand(?string $brandId, string $path): string
    {
        $brand = $brandId === null ? null : Brand::query()->find($brandId);

        $base = $brand === null ? null : $this->brandUrl->baseFor($brand);

        return $this->join($base, $path);
    }

    /**
     * The operator console's origin. A console-filed report has no brand to
     * ask, and a single-host install has no `admin_host` at all — both fall
     * back to the deployment's own URL rather than to a relative path.
     */
    private function onConsole(?string $brandId, string $path): string
    {
        $base = $brandId === null
            ? null
            : $this->operatorSettings->adminBaseUrlForBrand($brandId);

        return $this->join($base, $path);
    }

    private function join(?string $base, string $path): string
    {
        $base = rtrim($base ?? (string) config('app.url'), '/');

        return $base.'/'.ltrim($path, '/');
    }
}
